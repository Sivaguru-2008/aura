import json
from pathlib import Path
import numpy as np
from scipy import stats
from sklearn.linear_model import LogisticRegression

from aura.common.config import ARTIFACTS
from aura.common.mathx import softmax
from aura.ml.evaluation import v6_confirmatory as v6
from aura.ml.evaluation.matched_optimiser import _full_width_logits
from aura.ml.evaluation.v6_mechanism import _features
from aura.services.safety.calibration import fit_temperature, expected_calibration_error

OUT_DIR = Path(__file__).resolve().parent

def build_polynomial_features(X: np.ndarray, informative: int = 7) -> np.ndarray:
    """14 features: x_i and x_i^2 for i=1..informative."""
    Xi = X[:, :informative]
    return np.hstack([Xi, Xi ** 2])

def run_model(Ftr, ytr, Fc, yc, Ft, yt, C_grid=(0.001, 0.01, 0.1, 1.0, 10.0, 100.0)):
    best = None
    for C in C_grid:
        m = LogisticRegression(C=C, max_iter=5000, solver="lbfgs").fit(Ftr, ytr)
        Lc = _full_width_logits(m, Fc)
        T = fit_temperature(Lc, yc)
        Pc = np.array([softmax(r / T) for r in Lc])
        cal_nll = float(-np.log(np.clip(Pc[np.arange(len(yc)), yc], 1e-12, 1)).mean())
        if best is None or cal_nll < best[0]:
            best = (cal_nll, C, m, T)
    
    cal_nll, C, m, T = best
    Lt = _full_width_logits(m, Ft)
    Pt = np.array([softmax(r / T) for r in Lt])
    pnll = -np.log(np.clip(Pt[np.arange(len(yt)), yt], 1e-12, 1))
    acc = float((Pt.argmax(1) == yt).mean())
    ece = float(expected_calibration_error(Pt, yt))
    return {
        "selected_C": C,
        "cal_nll": round(cal_nll, 5),
        "temperature": round(float(T), 4),
        "test_nll": round(float(pnll.mean()), 5),
        "test_accuracy": round(acc, 5),
        "test_ece": round(ece, 5),
        "pnll": pnll,
        "probs": Pt,
    }

def main():
    Xtr, ytr, Xcal, ycal = v6.dev_splits()
    Xte, yte = v6.test_set()
    n = 8
    informative = 7

    print("Building features...")
    # 1. Order-1 trig features (14 features)
    Ftr_t1, _ = _features(Xtr, n, 1)
    keep_t1 = Ftr_t1.std(0) > 1e-12
    keep_t1[0] = False
    Ftr_t1, Fc_t1, Ft_t1 = Ftr_t1[:, keep_t1], _features(Xcal, n, 1)[0][:, keep_t1], _features(Xte, n, 1)[0][:, keep_t1]

    # 2. Order-2 trig features (105 features)
    Ftr_t2, _ = _features(Xtr, n, 2)
    keep_t2 = Ftr_t2.std(0) > 1e-12
    keep_t2[0] = False
    Ftr_t2, Fc_t2, Ft_t2 = Ftr_t2[:, keep_t2], _features(Xcal, n, 2)[0][:, keep_t2], _features(Xte, n, 2)[0][:, keep_t2]

    # 3. Polynomial features: x and x^2 (14 features)
    Ftr_poly = build_polynomial_features(Xtr, informative)
    Fc_poly = build_polynomial_features(Xcal, informative)
    Ft_poly = build_polynomial_features(Xte, informative)

    # 4. Standard linear features: x (7 features)
    Ftr_lin = Xtr[:, :informative]
    Fc_lin = Xcal[:, :informative]
    Ft_lin = Xte[:, :informative]

    models = {
        "order1_trig_lr": (Ftr_t1, Fc_t1, Ft_t1, int(keep_t1.sum())),
        "order2_trig_lr": (Ftr_t2, Fc_t2, Ft_t2, int(keep_t2.sum())),
        "poly14_lr": (Ftr_poly, Fc_poly, Ft_poly, Ftr_poly.shape[1]),
        "linear7_lr": (Ftr_lin, Fc_lin, Ft_lin, Ftr_lin.shape[1]),
    }

    # Load C2 tuned VQC and tuned PoE test pnll for comparisons
    c2_vqc_eval = np.load(OUT_DIR / "c2_winner_vqc_seed7_eval.npz") if (OUT_DIR / "c2_winner_vqc_seed7_eval.npz").exists() else None
    c2_poe_eval = np.load(OUT_DIR / "c2_tuned_poe_seed7_eval.npz")

    # If c2_vqc_eval not yet generated by seed 7, load from PART / C2_quantum_20.npz
    if c2_vqc_eval is None:
        c2_grid = json.loads((ARTIFACTS / "v6" / "C2_quantum_grid.json").read_text())
        c2_winner_rec = min(c2_grid, key=lambda r: r["best_calibration_nll"])
        fwd = v6._load_forward(v6._c2_build("quantum", c2_winner_rec["config"], Xtr.shape[1]), ARTIFACTS / "v6" / c2_winner_rec["file"])
        Lcal, Lte = v6._logits(fwd, Xcal), v6._logits(fwd, Xte)
        T_vqc = fit_temperature(Lcal, ycal)
        P_vqc = np.array([softmax(r / T_vqc) for r in Lte])
        pnll_vqc = -np.log(np.clip(P_vqc[np.arange(len(yte)), yte], 1e-12, 1))
    else:
        pnll_vqc = c2_vqc_eval["pnll"]
    
    pnll_poe = c2_poe_eval["pnll"]

    results = {}
    rng = np.random.default_rng(0)
    N_BOOT = 2000
    boot_idx = [rng.integers(0, len(yte), len(yte)) for _ in range(N_BOOT)]

    for name, (Ftr, Fc, Ft, n_feat) in models.items():
        print(f"Fitting {name} ({n_feat} features)...")
        res = run_model(Ftr, ytr, Fc, ycal, Ft, yte)
        pnll_m = res["pnll"]

        # Delta vs Tuned VQC (VQC - Model: positive means Model is better than VQC)
        d_vs_vqc = pnll_vqc - pnll_m
        se_vqc = float(d_vs_vqc.std(ddof=1) / np.sqrt(len(d_vs_vqc)))
        ci_vqc = [round(float(d_vs_vqc.mean() - 1.96 * se_vqc), 5), round(float(d_vs_vqc.mean() + 1.96 * se_vqc), 5)]

        # Delta vs Tuned PoE (PoE - Model: positive means Model is better than PoE)
        d_vs_poe = pnll_poe - pnll_m
        se_poe = float(d_vs_poe.std(ddof=1) / np.sqrt(len(d_vs_poe)))
        ci_poe = [round(float(d_vs_poe.mean() - 1.96 * se_poe), 5), round(float(d_vs_poe.mean() + 1.96 * se_poe), 5)]

        results[name] = {
            "features": n_feat,
            "selected_C": res["selected_C"],
            "temperature": res["temperature"],
            "test_nll": res["test_nll"],
            "test_accuracy": res["test_accuracy"],
            "test_ece": res["test_ece"],
            "vqc_minus_model_nll": round(float(d_vs_vqc.mean()), 5),
            "vqc_minus_model_ci95": ci_vqc,
            "poe_minus_model_nll": round(float(d_vs_poe.mean()), 5),
            "poe_minus_model_ci95": ci_poe,
        }
        print(f"  {name}: NLL={res['test_nll']:.5f}, Acc={res['test_accuracy']:.4f}, VQC - Model = {d_vs_vqc.mean():+.5f} (CI: {ci_vqc})")

    out_file = OUT_DIR / "m2_completeness.json"
    out_file.write_text(json.dumps(results, indent=2))
    print(f"\nWrote {out_file}")

if __name__ == "__main__":
    main()
